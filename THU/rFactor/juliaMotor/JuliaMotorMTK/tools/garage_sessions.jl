# SETUPMODEL-1: write src/garage_sessions.toml -- the two car setups julia races (iRacing default, WW103) as garage
# knobs + iRacing's own derived numbers, for the launcher's Garage tab (which cannot read an .ibt). The sim itself uses
# the session it loaded; this file is the launcher's copy of the same thing.
#   julia --project=JuliaMotorMTK JuliaMotorMTK/tools/garage_sessions.jl <default.ibt> <ww103.ibt>
using TOML
include(joinpath(@__DIR__, "..", "src", "ibt.jl")); using .IBT
include(joinpath(@__DIR__, "..", "src", "setup.jl")); using .Setup
include(joinpath(@__DIR__, "..", "src", "garage.jl")); using .Garage

out = Dict{String,Any}("note" => "generated by tools/garage_sessions.jl -- do not edit")
for (key, fn) in zip(("default", "ww103"), ARGS)
    sp = Setup.setup_params(IBT.session_yaml(IBT.ibt_open(fn)))
    K = Garage.calibrate_session(sp)
    c4(d) = [d[:LF], d[:RF], d[:LR], d[:RR]]
    knobs = Dict{String,Any}()
    for f in Garage.KNOB_FIELDS
        v = getfield(K, f); knobs[String(f)] = v isa Tuple ? collect(v) : v
    end
    out[key] = Dict{String,Any}("source" => basename(fn), "knobs" => knobs,
        "derived" => Dict{String,Any}("cw" => c4(sp.corner_weight_N), "rh" => c4(sp.ride_height_mm),
                                      "shock" => [x[1] for x in c4(sp.shock_defl_mm)], "camber" => c4(sp.camber_deg),
                                      "toe_front" => sp.toe_front_mm, "cross" => sp.cross_weight_pct))
    println(key, " <- ", basename(fn), "   model at the session: ", Garage.describe_derived(Garage.solve_static(K)))
end
open(io -> TOML.print(io, out; sorted = true), joinpath(@__DIR__, "..", "src", "garage_sessions.toml"), "w")
