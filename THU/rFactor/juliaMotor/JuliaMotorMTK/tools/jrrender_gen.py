#!/usr/bin/env python3
"""E80-S10: build JRRender/src/workload.jl from --trace-compile logs of sim launches.

Keeps the precompile statements that name the render/track modules (Render, GPL3DO, GPLMip, GPLDat, GPLTrack, GPLWall,
RoadCurve) and nothing of the sim script (Main.) or of the other loose modules, which the package cannot see.
Closures of these modules are kept: their names change with edits, and a stale one is skipped by the package.

usage: jrrender_gen.py OUT.jl TRACE.jl [TRACE.jl ...]
"""
import re, sys
OURS = r'\b(Render|GPL3DO|GPLMip|GPLDat|GPLTrack|GPLWall|RoadCurve)\.'
OTHERS = (r'\b(JoyCfg|FFB|GPLAI|RaceAI|EngineAudio|NetPlay|Setup|SetupTab|IBT|SuspPose|WreckSeal|PeopleFilter|GPLLP|'
          r'StepGuard|SolidGeom|SeriousGamesWeek|DriveRT3D|DriveRT|JRPhysics)\.')
keep = set()
for path in sys.argv[2:]:
    for l in open(path, encoding="utf-8", errors="replace"):
        l = re.sub(r"^#=\s*[0-9.]+ ms =#\s*", "", l).strip()
        if l.startswith("precompile(") and re.search(OURS, l) and "Main." not in l and not re.search(OTHERS, l):
            keep.add(l)
with open(sys.argv[1], "w") as f:
    f.write("# GENERATED by JuliaMotorMTK/tools/jrrender_gen.py from sim launch traces -- do not edit by hand\n")
    for l in sorted(keep): f.write(l + "\n")
print(f"{len(keep)} statements -> {sys.argv[1]}")
