# IRPLAN-3 Part A: the PO's iRacing setup SHEETS (.htm, plain text) -> frames_sheets.csv, the same columns as
# 261017/garage/frames_{screens,ibt}.csv, so garage_fit_261017.jl can take them as exact frames (a sheet is the
# finished solve: no lagging-screenshot asterisk problem).  Also writes knobs_sheets.csv: every value on every sheet.
#   python3 -I 261018/ingest/sheet_frames.py <sheets dir> <out dir>
import re, sys, os, glob, html, csv
SRC, OUT = sys.argv[1], sys.argv[2]
SIDE = {'LEFT FRONT': 'LeftFront', 'LEFT REAR': 'LeftRear', 'RIGHT FRONT': 'RightFront', 'RIGHT REAR': 'RightRear',
        'FRONT': 'Front', 'REAR': 'Rear', 'Transmission': 'Transmission', 'Differential': 'Differential'}

def sheet(p):
    t = open(p, encoding='latin-1').read()
    t = re.sub(r'<br\s*/?>', '\n', t); t = re.sub(r'<[^>]+>', ' ', t); t = html.unescape(t)
    t = t.split(' Notes:')[0]
    d, sec, seen, key = {}, None, set(), None
    for raw in t.split('\n'):
        ln = re.sub(r'[ \t]+', ' ', raw).strip()
        if not ln: continue
        m = re.fullmatch(r'(LEFT FRONT|LEFT REAR|RIGHT FRONT|RIGHT REAR|FRONT|REAR|Transmission|Differential):', ln)
        if m:
            s = SIDE[m.group(1)]
            grp = 'Chassis' if (s in seen or s in ('Front', 'Rear')) else ('Drivetrain' if s in ('Transmission', 'Differential') else 'Tires')
            seen.add(s); sec = grp + '.' + s; continue
        m = re.match(r'lotus49 setup: (.*)', ln)
        if m: d['name'] = m.group(1).strip(); continue
        if sec is None: continue
        k, sep, v = ln.partition(':')
        if sep and not re.fullmatch(r'[\d.]+ ?\S*', k):
            key = sec + '.' + re.sub(r'[^A-Za-z]', '', k.title()); d[key] = v.strip()
        elif key:                                   # continuation line ("of 104.6 mm", "126.0 Km/h", "39C")
            d[key] += ' ' + ln
    return d

num = lambda s: float(re.search(r'[-+]?\d+(?:\.\d+)?', s).group()) if re.search(r'\d', s) else float('nan')
C = ['LeftFront', 'RightFront', 'LeftRear', 'RightRear']
cols = 'snip,stale,pLF,pRF,pLR,pRR,kLF,kRF,kLR,kRR,packLF,fuel,fdia,farm,rdia,rarm,cwLF,cwRF,cwLR,cwRR,rhLF,rhRF,rhLR,rhRR,shLF,shRF,shLR,shRR,caLF,caRF,caLR,caRR,cross,toeF,maxLF,toeR,packRF,packLR,packRR,prLF,prRF,prLR,prRR,src'
frames = ['# generated by 261018/ingest/sheet_frames.py from the PO\'s 261018 setup sheets (IRPLAN-3 Part A); exact solves', cols]
sheets = {}
for p in sorted(glob.glob(os.path.join(SRC, '*.htm'))):
    d = sheet(p); sheets[os.path.basename(p)] = d
    ch = lambda c, k: d['Chassis.%s.%s' % (c, k)]
    dia = lambda s: 0.0 if 'isc' in s else num(s)
    row = ['sheet', 0] + [num(ch(c, 'SpringPerchOffset')) for c in C] + [num(ch(c, 'SpringRate')) for c in C]
    row += [num(ch('LeftFront', 'Packer')), num(d['Chassis.Rear.FuelLevel']), dia(d['Chassis.Front.ArbDiameter']),
            d['Chassis.Front.ArbArms'], dia(d['Chassis.Rear.ArbDiameter']), d['Chassis.Rear.ArbArms']]
    row += [num(ch(c, 'CornerWeight')) for c in C] + [num(ch(c, 'RideHeight')) for c in C]
    row += [num(ch(c, 'ShockDeflection')) for c in C] + [num(ch(c, 'Camber')) for c in C]
    row += [num(d['Chassis.Front.CrossWeight']), num(d['Chassis.Front.ToeIn']),
            float(re.findall(r'[\d.]+', ch('LeftFront', 'ShockDeflection'))[1]), num(d['Chassis.Rear.ToeIn'])]
    row += [num(ch(c, 'Packer')) for c in C[1:]] + [num(d['Tires.%s.ColdPressure' % c]) for c in C]
    row += ['"261018/sheets/' + os.path.basename(p) + '"']
    frames.append(','.join(str(x) for x in row))
open(os.path.join(OUT, 'frames_sheets.csv'), 'w').write('\n'.join(frames) + '\n')
keys = sorted({k for d in sheets.values() for k in d if not re.search('Last|Tread', k)})
with open(os.path.join(OUT, 'knobs_sheets.csv'), 'w', newline='') as f:
    w = csv.writer(f); w.writerow(['sheet'] + keys)
    for n, d in sheets.items():
        w.writerow([n] + [d.get(k, '') for k in keys])
print(len(sheets), 'sheets ->', OUT)
