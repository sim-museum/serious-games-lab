# SETUPMODEL-1: every distinct CarSetup in the gold .ibt store -> frames_ibt.csv (same columns as frames_screens.csv)
import struct, sys, re, os, glob
ROOT = sys.argv[1]
def yaml(p):
    b = open(p,'rb').read(3_000_000)
    ln, off = struct.unpack_from('<ii', b, 16)
    return b[off:off+ln].decode('latin1')
def cs(t):
    t=t[t.find('CarSetup:'):]; d={}; path=[]
    for line in t.split('\n')[1:]:
        if not line.strip(): continue
        ind=len(line)-len(line.lstrip())
        if ind==0: break
        k,_,v=line.strip().partition(':'); path=path[:ind-1]+[k]
        if v.strip(): d['.'.join(path)]=v.strip()
    return d
num=lambda s: float(re.search(r'[-+]?\d+(?:\.\d+)?', s).group()) if re.search(r'\d', s) else float('nan')
C=['LeftFront','RightFront','LeftRear','RightRear']
seen={}
for p in sorted(glob.glob(ROOT+'/**/*.ibt', recursive=True)):
    try: d=cs(yaml(p))
    except Exception: continue
    if 'Chassis.LeftFront.CornerWeight' not in d: continue
    key=tuple(sorted((k,v) for k,v in d.items() if not re.search('Last|Tread|UpdateCount|Bump|Rebound|Brake|Diff|Trans|Steering',k)))
    seen.setdefault(key,os.path.relpath(p,ROOT))
cols='snip,stale,pLF,pRF,pLR,pRR,kLF,kRF,kLR,kRR,packLF,fuel,fdia,farm,rdia,rarm,cwLF,cwRF,cwLR,cwRR,rhLF,rhRF,rhLR,rhRR,shLF,shRF,shLR,shRR,caLF,caRF,caLR,caRR,cross,toeF,maxLF,toeR,packRF,packLR,packRR,prLF,prRF,prLR,prRR,src'
print('# generated by ibt_frames.py from the gold .ibt store; exact garage values (display resolution)')
print(cols)
for key,src in seen.items():
    d=dict(key); ch=lambda c,k: d['Chassis.%s.%s'%(c,k)]
    dia=lambda s: 0.0 if 'isc' in s else num(s)
    row=['ibt',0]+[num(ch(c,'SpringPerchOffset')) for c in C]+[num(ch(c,'SpringRate')) for c in C]
    row+=[num(ch('LeftFront','Packer')), num(d['Chassis.Rear.FuelLevel']), dia(d['Chassis.Front.ArbDiameter']), d['Chassis.Front.ArbArms'],
          dia(d['Chassis.Rear.ArbDiameter']), d['Chassis.Rear.ArbArms']]
    row+=[num(ch(c,'CornerWeight')) for c in C]+[num(ch(c,'RideHeight')) for c in C]
    row+=[num(ch(c,'ShockDeflection')) for c in C]+[num(ch(c,'Camber')) for c in C]
    row+=[num(d['Chassis.Front.CrossWeight']), num(d['Chassis.Front.ToeIn']), float(re.findall(r'[\d.]+',ch('LeftFront','ShockDeflection'))[1]),
          num(d['Chassis.Rear.ToeIn'])]+[num(ch(c,'Packer')) for c in C[1:]]+[num(d['Tires.%s.ColdPressure'%c]) for c in C]+['"'+src+'"']
    print(','.join(str(x) for x in row))
